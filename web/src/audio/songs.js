/**
 * Public-domain piano pieces for the login hero.
 *
 * COPYRIGHT: every piece here is a public-domain composition — Pachelbel
 * (d. 1706), Bach (d. 1750), Beethoven (d. 1827), all published long before
 * 1928. The audio is SYNTHESIZED in-browser from these note numbers (see
 * PianoSynth.js), so there is no sound-recording copyright either: no sample,
 * no master, nothing licensed.
 *
 * TWO HANDS, ONE RIG. The hero renders a single hand sitting at the bass end of
 * the keyboard, so it plays the LEFT-hand part — bass notes and chords. The
 * right-hand melody still sounds, it just has no fingers to drive: there is no
 * second hand to render, and faking it on the left hand would look worse than
 * leaving it to the ear. Notes are therefore tagged "L" (audible AND played by
 * the visible hand) or "R" (audible only). Pieces are chosen for a left-hand
 * part that is worth watching — chords and arpeggios rather than a single line.
 *
 * Authoring format — `{ id, title, composer, step, notes }` where a note is
 * `[unit, midi, durUnits, hand]` and `step` is seconds per unit. Times in units
 * keep the data readable (a unit is whatever subdivision the piece wants);
 * compileSong() converts to seconds. Pieces built on a repeating figure are
 * generated by a small function rather than typed out — same data, far less
 * room for a transcription slip.
 */

// --- Canon in D (Pachelbel) -------------------------------------------------
// The ground bass everyone knows, with a chord on the off-beat so the left hand
// has something to grip. Cycle 1 is bass alone; the melody enters in cycle 2,
// which is how the canon itself builds.
function canonInD() {
  const bass = [50, 45, 47, 42, 43, 38, 43, 45]; // D A B F# G D G A
  const chords = [
    [54, 57, 62], // D
    [49, 52, 57], // A
    [50, 54, 59], // Bm
    [49, 54, 57], // F#m
    [50, 55, 59], // G
    [54, 57, 62], // D
    [50, 55, 59], // G
    [49, 52, 57], // A
  ];
  const melody = [78, 76, 74, 73, 71, 69, 71, 73];
  const notes = [];
  for (let cycle = 0; cycle < 2; cycle++) {
    for (let i = 0; i < 8; i++) {
      const u = cycle * 32 + i * 4;
      notes.push([u, bass[i], 4, "L"]);
      for (const m of chords[i]) notes.push([u + 2, m, 2, "L"]);
      if (cycle === 1) notes.push([u, melody[i], 4, "R"]);
    }
  }
  return notes;
}

// --- Prelude in C (Bach, WTC I) ---------------------------------------------
// Every bar is one broken chord played twice: the left hand lays down two low
// notes and holds them while the right hand arpeggiates above.
function preludeInC() {
  const bars = [
    { L: [48, 52], R: [55, 60, 64] }, // C
    { L: [48, 50], R: [57, 62, 65] }, // Dm7/C
    { L: [47, 50], R: [55, 62, 65] }, // G7/B
    { L: [48, 52], R: [55, 60, 64] }, // C
  ];
  const notes = [];
  bars.forEach((bar, b) => {
    for (let half = 0; half < 2; half++) {
      const u = b * 16 + half * 8;
      notes.push([u, bar.L[0], 8, "L"]); // bass rings under the whole figure
      notes.push([u + 1, bar.L[1], 7, "L"]);
      bar.R.forEach((m, i) => notes.push([u + 2 + i, m, 2, "R"]));
      bar.R.forEach((m, i) => notes.push([u + 5 + i, m, 2, "R"]));
    }
  });
  return notes;
}

// --- Ode to Joy (Beethoven) -------------------------------------------------
// Melody in the right hand over block chords in the left — the standard piano
// arrangement, and the clearest "hand plays chords" of the four.
function odeToJoy() {
  const melody = [
    [0, 64, 1], [1, 64, 1], [2, 65, 1], [3, 67, 1],
    [4, 67, 1], [5, 65, 1], [6, 64, 1], [7, 62, 1],
    [8, 60, 1], [9, 60, 1], [10, 62, 1], [11, 64, 1],
    [12, 64, 1.5], [13.5, 62, 0.5], [14, 62, 2],
    [16, 64, 1], [17, 64, 1], [18, 65, 1], [19, 67, 1],
    [20, 67, 1], [21, 65, 1], [22, 64, 1], [23, 62, 1],
    [24, 60, 1], [25, 60, 1], [26, 62, 1], [27, 64, 1],
    [28, 62, 1.5], [29.5, 60, 0.5], [30, 60, 2],
  ];
  const C = [48, 52, 55];
  const G = [43, 47, 50];
  // one chord every half bar, following the tune's harmony
  const plan = [
    [0, C], [2, C], [4, C], [6, G], [8, C], [10, G], [12, G], [14, C],
    [16, C], [18, C], [20, C], [22, G], [24, C], [26, G], [28, G], [30, C],
  ];
  const notes = melody.map(([u, m, d]) => [u, m, d, "R"]);
  for (const [u, chord] of plan) for (const m of chord) notes.push([u, m, 2, "L"]);
  return notes;
}

